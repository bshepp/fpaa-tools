"""
FPAA Configuration File Parser

Parses Anadigm Hex Files (.ahf) generated by AnadigmDesigner2 / DynAMx
Design Lab and the StateDrivenCode.c arrays generated for embedded use.

AHF format (verified against the bundled examples/4osc.ahf and pikapy's
spitest.py:130-133): plain ASCII, one byte per line, no record framing,
no checksums. The file already contains the five leading 0x00 NULL bytes
that ANU002 specifies before the SYNC byte (0xD5), and concatenates one
per-chip primary configuration frame for each FPAA in the chain.

Per-chip frame structure (per AN310 §3.1, ANU002, and ABK reference firmware):
    Offset  Bytes        Meaning
    ------  -----------  ------------------------------------------
    0       0xD5         SYNC byte
    1-4     0xB7 0x20    JTAG bytes (AN231E04: 0xB7 0x20 0x01 0x00)
            0x01 0x00
    5       0x01..0xFE   Chip address (8-bit, allocated by host)
    6       0xC1 / 0x81  Control byte (0xC1 = enable ACT pull-up,
                                       0x81 = disable for non-first chip)
    7..n-2  data blocks  Each block: byte_addr, bank_addr, count, data..., 0x2A
    n-1     0x00         Final NULL byte (separator before next chip)
"""

import re
from typing import List, Optional, Dict
from dataclasses import dataclass
from pathlib import Path


@dataclass
class ConfigBlock:
    """A block of configuration data for a specific memory bank/region."""
    byte_address: int
    bank_address: int
    data: bytes

    @property
    def length(self) -> int:
        return len(self.data)


@dataclass
class FPAAConfig:
    """Per-chip primary configuration extracted from an AHF."""
    chip_id: int
    blocks: List[ConfigBlock]
    raw_data: bytes

    @property
    def total_bytes(self) -> int:
        return len(self.raw_data)

    def get_block(self, bank: int) -> Optional[ConfigBlock]:
        for block in self.blocks:
            if block.bank_address == bank:
                return block
        return None


def load_ahf_bytes(filepath: str) -> bytes:
    """
    Read an AHF file and return its full byte content as a single stream.

    This is the canonical loader for sending configurations to hardware:
    the bytes returned should be passed straight to FPAAChain.send_bytes()
    without any reframing.
    """
    path = Path(filepath)
    if not path.exists():
        raise FileNotFoundError(f"AHF file not found: {filepath}")

    out = bytearray()
    with open(path, 'r') as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            out.append(int(line, 16))
    return bytes(out)


def split_ahf_by_chip(data: bytes) -> List[FPAAConfig]:
    """
    Split a raw AHF byte stream into per-chip primary configurations.

    Each chip's frame begins with the SYNC byte 0xD5 and ends just before
    the next 0xD5 (or end-of-stream). Useful for inspection/debugging — not
    needed for actually sending the configuration to hardware.
    """
    configs: List[FPAAConfig] = []

    # Find every SYNC byte position
    sync_positions = [i for i, b in enumerate(data) if b == 0xD5]
    if not sync_positions:
        return configs

    boundaries = sync_positions + [len(data)]
    for i in range(len(sync_positions)):
        start = boundaries[i]
        end = boundaries[i + 1]
        frame = data[start:end]
        configs.append(parse_bitstream(frame, chip_id=_chip_id_from_frame(frame)))
    return configs


def chip_frame(data: bytes, addr: int) -> bytes:
    """Extract the single primary-config frame from a PER-CHIP AHF byte stream
    and set its chain address.

    A per-chip export (AD2 ``WriteConfigData`` fmt 0) is ``[0x00 preamble][one
    0xD5 frame]``, so the frame is everything from the first 0xD5. This is
    deliberately NOT built on split_ahf_by_chip(), which splits on every 0xD5
    and mis-fires when configuration data happens to contain that byte.
    """
    start = data.find(0xD5)
    if start < 0:
        raise ValueError("no 0xD5 frame sync in AHF data")
    f = bytearray(data[start:])
    if len(f) < 7 or f[6] != 0xC1:
        ctrl = f"0x{f[6]:02X}" if len(f) > 6 else "missing"
        raise ValueError(f"control byte {ctrl} != 0xC1 (not a primary-config frame?)")
    if not 1 <= addr <= 0xFE:
        raise ValueError(f"chain address {addr} out of range 1..254")
    f[5] = addr
    return bytes(f)


def write_ahf(path, data: bytes) -> Path:
    """Write a byte stream as an AHF (ASCII hex, one byte per line)."""
    path = Path(path)
    path.write_text("\n".join(f"{b:02X}" for b in data) + "\n")
    return path


def assemble_chain(sources, out_path=None, n_chips: int = 4) -> bytes:
    """Build a daisy-chain primary configuration from per-chip AHFs.

    ``sources`` is a sequence of per-chip AHF paths or byte streams, in chain
    order; frame ``i`` gets chain address ``i + 1``. A single source (not a
    list) is replicated to ``n_chips`` addresses -- the usual way to get N
    independent measurements of one design, and to make ACTIVATE assert.

    Returns ``5 NULL bytes + frames``; also writes it to ``out_path`` as an AHF
    if given.
    """
    if isinstance(sources, (str, Path, bytes, bytearray)):
        sources = [sources] * n_chips
    frames = []
    for i, src in enumerate(sources):
        is_bytes = isinstance(src, (bytes, bytearray))
        data = bytes(src) if is_bytes else load_ahf_bytes(src)
        try:
            frames.append(chip_frame(data, i + 1))
        except ValueError as e:
            label = "bytes" if is_bytes else str(src)
            raise ValueError(f"chain position {i} ({label}): {e}") from None
    chain = bytes(5) + b"".join(frames)
    if out_path is not None:
        write_ahf(out_path, chain)
    return chain


def load_ahf_file(filepath: str) -> List[FPAAConfig]:
    """
    Load an AHF file and split it into per-chip configurations.

    Backwards-compatible name; replaces the previous Intel-HEX-based
    implementation (the prior version did not parse real AHF files since
    AHF is not Intel HEX).

    Returns a list of FPAAConfig, one per chip frame found.
    """
    data = load_ahf_bytes(filepath)
    return split_ahf_by_chip(data)


def _chip_id_from_frame(frame: bytes) -> int:
    """Read the chip address byte (offset 5) from a per-chip frame."""
    if len(frame) >= 6 and frame[0] == 0xD5:
        return frame[5]
    return 0


def parse_bitstream(data: bytes, chip_id: int = 1) -> FPAAConfig:
    """
    Parse one per-chip primary configuration frame into ConfigBlocks.

    Per the AN231E04 configuration format used by AnadigmDesigner2:
      Offset  Field
      0       0xD5 SYNC
      1-4     JTAG (0xB7 0x20 0x01 0x00 for AN231E04)
      5       chip address
      6       control byte
      7..     repeating data blocks of:
                 byte_address (1)
                 bank_address (1)
                 byte_count   (1)
                 data         (byte_count bytes)
                 0x2A check byte
              terminating with a final 0x00 separator before the next chip.
    """
    blocks: List[ConfigBlock] = []

    sync_idx = data.find(0xD5)
    if sync_idx == -1:
        return FPAAConfig(chip_id=chip_id, blocks=[], raw_data=data)

    # Skip past sync(1) + JTAG(4) + chip_id(1) + control(1) = 7 bytes
    idx = sync_idx + 7
    while idx < len(data) - 3:
        byte_addr = data[idx]
        bank_addr = data[idx + 1]
        byte_count = data[idx + 2]

        # Block terminator (a single 0x00 byte after the last block)
        if byte_count == 0:
            break
        if idx + 3 + byte_count > len(data):
            break

        block_data = data[idx + 3:idx + 3 + byte_count]
        blocks.append(ConfigBlock(
            byte_address=byte_addr,
            bank_address=bank_addr,
            data=block_data,
        ))
        # Advance past data + check byte (0x2A)
        idx += 3 + byte_count + 1

    return FPAAConfig(
        chip_id=_chip_id_from_frame(data) or chip_id,
        blocks=blocks,
        raw_data=data,
    )


def load_state_driven_code(c_file: str) -> Dict[str, bytes]:
    """
    Parse a StateDrivenCode.c file (generated by AnadigmDesigner2) and
    return the embedded const byte arrays.

    Pattern matched: `const an_Byte ARRAY_NAME[] = { 0x.., 0x.., ... };`
    """
    path = Path(c_file)
    if not path.exists():
        raise FileNotFoundError(f"C file not found: {c_file}")

    with open(path, 'r') as f:
        content = f.read()

    pattern = r'const\s+an_Byte\s+(\w+)\[\]\s*=\s*\{([^}]+)\}'
    hex_pattern = r'0x([0-9A-Fa-f]{2})'

    configs: Dict[str, bytes] = {}
    for match in re.finditer(pattern, content, re.DOTALL):
        name = match.group(1)
        values_str = match.group(2)
        hex_values = re.findall(hex_pattern, values_str)
        if hex_values:
            configs[name] = bytes(int(h, 16) for h in hex_values)
    return configs


# ---------------------------------------------------------------------------
# Test/development helper: a minimal "blank" frame for one chip.
#
# The previous implementation used a hand-crafted byte sequence pulled from
# the legacy ABK firmware. Now that we have a real reference AHF on disk
# (examples/4osc.ahf), prefer using a real AHF for bring-up. The function
# below remains for compatibility but is marked as
# unverified-against-current-hardware.
# ---------------------------------------------------------------------------

def create_blank_config(chip_id: int = 1, first_in_chain: bool = True) -> bytes:
    """
    Build a minimal "blank" per-chip primary configuration frame.

    UNVERIFIED on PIKA hardware. The byte sequence below is taken from the
    QuadApex ABK v6.0.5 reference firmware (Software/.../main.c
    Blank_Config_Data, lines 63-68) and the AN231 detection block in
    abk.c. The legacy QuadApex board worked with this exact sequence.

    For first-light testing on PIKA, use the known-good examples/4osc.ahf
    via FPAAChain.configure_from_ahf().
    """
    control = 0xC1 if first_in_chain else 0x81
    return bytes([
        0x00, 0x00, 0x00, 0x00, 0x00,           # 5 NULL preamble (ANU002)
        0xD5, 0xB7, 0x20, 0x01, 0x00,           # SYNC + JTAG
        chip_id & 0xFF,
        control,
        0xC4, 0x00, 0x0E,                       # block: addr=4, bank=0, 14 bytes
        0x20, 0x04, 0x00, 0x02, 0x00, 0x00, 0x00, 0x40,
        0x00, 0x00, 0x51, 0xFF, 0x0F, 0xF1,
        0x2A,
        0x9E, 0x01, 0x02, 0x02, 0xFF,           # block: addr=0x1E, bank=1, 2 bytes
        0x2A,
        0x00,                                   # frame terminator
    ])
